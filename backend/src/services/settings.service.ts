export async function loadTemplateOverrides() {
  try {
    setTemplateOverrides((await EmailTemplateOverrideModel.find().lean()).map((o) => ({ template: o.template, subject: o.subject, intro: o.intro })));
  } catch (err) {
    logger.error({ err: { message: (err as Error).message } }, 'Could not load email template customisations');
  }
}

export async function listTemplates() {
  const saved = new Map((await EmailTemplateOverrideModel.find().lean()).map((o) => [o.template, o]));
  return TEMPLATE_CATALOG.map((t) => ({ template: t.template, label: t.label, subject: saved.get(t.template)?.subject ?? '', intro: saved.get(t.template)?.intro ?? '', customised: saved.has(t.template), preview: renderEmail(t.template, t.sample) }));
}

export async function saveTemplate(template: string, input: { subject: string; intro: string }, req: Request) {
  const entry = TEMPLATE_CATALOG.find((t) => t.template === template);
  if (!entry) throw ApiError.notFound('Template not found');
  if (!input.subject && !input.intro) await EmailTemplateOverrideModel.deleteOne({ template });
  else await EmailTemplateOverrideModel.updateOne({ template }, { $set: { ...input, updatedBy: oid(req.user!.id) } }, { upsert: true });
  await loadTemplateOverrides();
  await audit(actorFrom(req), 'settings.email_template_updated', { type: 'email_template', id: template }, req, { reset: !input.subject && !input.intro });
  return { template, subject: input.subject, intro: input.intro, preview: renderEmail(entry.template, entry.sample) };
}

// ---- Content pages ----

type Slug = (typeof PAGE_SLUGS)[number];
type PageInput = { title: string; intro: string; body: string; faqs: Array<{ question: string; answer: string }> };
const toPage = (p: Lean, admin = false) => ({
  slug: p.slug,
  title: p.title,
  intro: p.intro,
  body: p.body,
  faqs: p.faqs ?? [],
  updatedAt: p.updatedAt,
  ...(admin && { status: p.status, revisions: (p.revisions ?? []).map((r: Lean) => ({ id: String(r._id), title: r.title, savedAt: r.savedAt })) }),
});

export async function publicPage(slug: Slug) {
  const p = (await ContentPageModel.findOne({ slug, status: 'published' }).lean()) as Lean | null;
  if (!p) throw ApiError.notFound('Page not set up yet');
  return toPage(p);
}

export async function adminPages() {
  const pages = new Map(((await ContentPageModel.find().lean()) as Lean[]).map((p) => [p.slug, p]));
  return (['about', 'faq', 'privacy', 'terms', 'admission-process', 'contact'] as Slug[]).map((slug) => (pages.has(slug) ? toPage(pages.get(slug)!, true) : { slug, title: '', intro: '', body: '', faqs: [], updatedAt: null, status: 'default', revisions: [] }));
}

// Saves a page; the previous version goes to the (bounded) revision list.
export async function savePage(slug: Slug, input: PageInput, req: Request) {
  const before = (await ContentPageModel.findOne({ slug }).lean()) as Lean | null;
  const revision = before ? { title: before.title, intro: before.intro, body: before.body, faqs: before.faqs, savedAt: before.updatedAt, savedBy: before.updatedBy } : null;
  const updated = await ContentPageModel.findOneAndUpdate(
    { slug },
    { $set: { ...input, status: 'published', updatedBy: oid(req.user!.id) }, ...(revision && { $push: { revisions: { $each: [revision], $position: 0, $slice: 20 } } }) },
    { upsert: true, new: true, runValidators: true },
  ).lean();
  await audit(actorFrom(req), 'content.page_saved', { type: 'page', id: slug }, req);
  return toPage(updated as Lean, true);
}

export async function restoreRevision(slug: Slug, revisionId: string, req: Request) {
  const p = (await ContentPageModel.findOne({ slug }).lean()) as Lean | null;
  const r = p?.revisions?.find((x: Lean) => String(x._id) === revisionId);
  if (!r) throw ApiError.notFound('Version not found');
  return savePage(slug, { title: r.title, intro: r.intro, body: r.body, faqs: r.faqs ?? [] }, req);
}

// Back to the built-in text (the page document is removed; history stays in the audit log).
export async function resetPage(slug: Slug, req: Request) {
  await ContentPageModel.deleteOne({ slug });
  await audit(actorFrom(req), 'content.page_reset', { type: 'page', id: slug }, req);
  return { slug, reset: true };
}

// ---- Announcements ----

type Audience = (typeof AUDIENCES)[number];
const MAX_RECIPIENTS = 5000;
const active = (now = new Date()) => ({ status: 'active', startsAt: { $lte: now }, $or: [{ expiresAt: null }, { expiresAt: { $gt: now } }] });
const toAnnouncement = (a: Lean) => ({ id: String(a._id), title: a.title, body: a.body, audience: a.audience, sendEmail: a.sendEmail, startsAt: a.startsAt, expiresAt: a.expiresAt ?? null, status: a.status, emailedCount: a.emailedCount, createdAt: a.createdAt });

async function recipients(audience: Audience) {
  const filter: Record<string, unknown> = { role: 'student', status: 'active', anonymisedAt: null };
  if (audience === 'students_verified' || audience === 'students_open_enquiry') filter.emailVerifiedAt = { $ne: null };
  if (audience === 'students_open_enquiry') filter._id = { $in: await EnquiryModel.distinct('student', { status: { $nin: FINISHED_STATUSES } }) };
  return UserModel.find(filter).select('name email').limit(MAX_RECIPIENTS + 1).lean();
}

export async function createAnnouncement(input: { title: string; body: string; audience: Audience; sendEmail: boolean; expiresAt: Date | null }, req: Request) {
  if (input.audience === 'public' && input.sendEmail) throw new ApiError(422, 'VALIDATION_ERROR', 'Website banners are not emailed', [{ field: 'sendEmail', message: 'Website banners are not emailed' }]);
  const list = input.sendEmail ? await recipients(input.audience) : [];
  if (list.length > MAX_RECIPIENTS) throw new ApiError(422, 'TOO_MANY_RECIPIENTS', `More than ${MAX_RECIPIENTS} recipients. Narrow the audience.`);
  const a = await AnnouncementModel.create({ ...input, createdBy: oid(req.user!.id) });
  for (const u of list) {
    await safeEmail({ to: u.email, template: 'announcement', params: { name: u.name, title: input.title, body: input.body, link: frontendLink('/student') }, dedupeKey: `announce:${String(a._id)}:${String(u._id)}` });
  }
  await AnnouncementModel.updateOne({ _id: a._id }, { $set: { emailedCount: list.length } });
  await audit(actorFrom(req), 'content.announcement_created', { type: 'announcement', id: String(a._id) }, req, { audience: input.audience, emailed: list.length });
  return { ...toAnnouncement(a.toObject() as Lean), emailedCount: list.length };
}

export async function adminAnnouncements({ page, limit }: { page: number; limit: number }) {
  const [items, total] = await Promise.all([AnnouncementModel.find().sort({ createdAt: -1 }).skip((page - 1) * limit).limit(limit).lean(), AnnouncementModel.countDocuments()]);
  return { items: (items as Lean[]).map(toAnnouncement), meta: pageMeta(page, limit, total) };
}

export async function withdrawAnnouncement(id: string, req: Request) {
  const a = await AnnouncementModel.findByIdAndUpdate(id, { $set: { status: 'withdrawn' } }, { new: true }).lean();
  if (!a) throw ApiError.notFound('Announcement not found');
  await audit(actorFrom(req), 'content.announcement_withdrawn', { type: 'announcement', id }, req);
  return toAnnouncement(a as Lean);
}

export async function publicBanners() {
  return ((await AnnouncementModel.find({ ...active(), audience: 'public' }).sort({ startsAt: -1 }).limit(3).lean()) as Lean[]).map((a) => ({ id: String(a._id), title: a.title, body: a.body }));
}

// The announcements a signed-in student should see on their dashboard.
export async function myAnnouncements(req: Request) {
  const user = await UserModel.findById(req.user!.id).select('emailVerifiedAt').lean();
  const audiences: Audience[] = ['students_all'];
  if (user?.emailVerifiedAt) audiences.push('students_verified');
  if (await EnquiryModel.exists({ student: req.user!.id, status: { $nin: FINISHED_STATUSES } })) audiences.push('students_open_enquiry');
  return ((await AnnouncementModel.find({ ...active(), audience: { $in: audiences } }).sort({ startsAt: -1 }).limit(10).lean()) as Lean[]).map((a) => ({ id: String(a._id), title: a.title, body: a.body, startsAt: a.startsAt }));
}
