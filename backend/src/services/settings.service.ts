// ---- Organisation details (shown on the contact page and in the footer) ----

const ORG_DEFAULTS = { name: '', supportEmail: '', supportPhone: '', whatsapp: '', address: '', officeHours: '', instagram: '', facebook: '' };

export async function getSiteSettings() {
  const s = await SiteSettingsModel.findById('site').lean();
  return { organisation: { ...ORG_DEFAULTS, ...(s?.organisation ?? {}) }, crm: { autoAssign: Boolean(s?.crm?.autoAssign) }, updatedAt: s?.updatedAt ?? null };
}

// What visitors may see (no internal settings).
export async function publicSiteSettings() {
  const { organisation, updatedAt } = await getSiteSettings();
  return { organisation, updatedAt };
}

export async function updateSiteSettings(organisation: Partial<typeof ORG_DEFAULTS> = {}, req: Request, crm?: { autoAssign?: boolean }) {
  const set: Record<string, unknown> = Object.fromEntries(Object.entries(organisation).map(([k, v]) => [`organisation.${k}`, v]));
  if (crm?.autoAssign !== undefined) set['crm.autoAssign'] = crm.autoAssign;
  await SiteSettingsModel.updateOne({ _id: 'site' }, { $set: { ...set, updatedBy: oid(req.user!.id) } }, { upsert: true, runValidators: true });
  await audit(actorFrom(req), 'settings.organisation_updated', { type: 'settings', id: 'site' }, req, { fields: [...Object.keys(organisation), ...(crm ? Object.keys(crm).map((k) => `crm.${k}`) : [])] });
  return getSiteSettings();
}

