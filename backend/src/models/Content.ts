import mongoose, { type InferSchemaType } from 'mongoose';

// ---- Organisation settings (one document) ----

const siteSettingsSchema = new mongoose.Schema(
  {
    _id: { type: String, default: 'site' },
    organisation: {
      name: { type: String, trim: true, maxlength: 120, default: '' },
      supportEmail: { type: String, trim: true, lowercase: true, maxlength: 254, default: '' },
      supportPhone: { type: String, trim: true, maxlength: 30, default: '' },
      whatsapp: { type: String, trim: true, maxlength: 30, default: '' },
      address: { type: String, trim: true, maxlength: 400, default: '' },
      officeHours: { type: String, trim: true, maxlength: 200, default: '' },
      // Official social media pages (footer and contact page).
      instagram: { type: String, trim: true, maxlength: 300, default: '' },
      facebook: { type: String, trim: true, maxlength: 300, default: '' },
    },
    // Enquiry handling: automatic assignment of new enquiries to the least busy active counsellor.
    crm: { autoAssign: { type: Boolean, default: false } },
    updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  },
  { timestamps: true },
);
export const SiteSettingsModel = mongoose.model('SiteSettings', siteSettingsSchema, 'siteSettings');

// ---- Email template customisation ----

// Admins may change a template's subject and add an introductory paragraph. Links, references and every other part
// of the message stay generated by the system, so a customisation cannot break a verification or reset link.
const emailTemplateOverrideSchema = new mongoose.Schema(
  {
    template: { type: String, required: true, maxlength: 60 },
    subject: { type: String, trim: true, maxlength: 160, default: '' },
    intro: { type: String, trim: true, maxlength: 1000, default: '' },
    updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  },
  { timestamps: true },
);
emailTemplateOverrideSchema.index({ template: 1 }, { unique: true, name: 'template_override_unique' });
export const EmailTemplateOverrideModel = mongoose.model('EmailTemplateOverride', emailTemplateOverrideSchema, 'emailTemplateOverrides');

// ---- Editable content pages ----

export const PAGE_SLUGS = ['about', 'faq', 'privacy', 'terms', 'admission-process', 'contact'] as const;

const pageBody = {
  title: { type: String, required: true, trim: true, maxlength: 120 },
  intro: { type: String, trim: true, maxlength: 600, default: '' },
  // A small, safe Markdown subset rendered by the frontend without HTML (headings, lists, bold, https links).
  body: { type: String, trim: true, maxlength: 30_000, default: '' },
  faqs: { type: [{ _id: false, question: { type: String, maxlength: 300 }, answer: { type: String, maxlength: 2000 } }], default: [] },
};
const contentPageSchema = new mongoose.Schema(
  {
    slug: { type: String, enum: PAGE_SLUGS, required: true },
    ...pageBody,
    status: { type: String, enum: ['published', 'draft'], default: 'published' },
    updatedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
    // Previous versions (most recent first, bounded) so a change can be undone.
    revisions: {
      type: [{ ...pageBody, savedAt: { type: Date, default: () => new Date() }, savedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null } }],
      default: [],
      validate: (v: unknown[]) => v.length <= 20,
    },
  },
  { timestamps: true },
);
contentPageSchema.index({ slug: 1 }, { unique: true, name: 'content_page_slug_unique' });
export type ContentPage = InferSchemaType<typeof contentPageSchema>;
export const ContentPageModel = mongoose.model('ContentPage', contentPageSchema, 'contentPages');

// ---- Announcements ----

export const AUDIENCES = ['public', 'students_all', 'students_verified', 'students_open_enquiry'] as const;

const announcementSchema = new mongoose.Schema(
  {
    title: { type: String, required: true, trim: true, maxlength: 120 },
    body: { type: String, required: true, trim: true, maxlength: 2000 },
    // public: a banner on the website (never emailed); students_*: students' dashboards (and email if chosen).
    audience: { type: String, enum: AUDIENCES, required: true },
    sendEmail: { type: Boolean, default: false },
    startsAt: { type: Date, default: () => new Date() },
    expiresAt: { type: Date, default: null },
    status: { type: String, enum: ['active', 'withdrawn'], default: 'active' },
    emailedCount: { type: Number, default: 0 },
    createdBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  },
  { timestamps: true },
);
announcementSchema.index({ status: 1, audience: 1, startsAt: -1 }, { name: 'announcement_active' });
export const AnnouncementModel = mongoose.model('Announcement', announcementSchema, 'announcements');

// ---- Payments (consultancy service charge, via Razorpay) ----

export const PAYMENT_STATUSES = ['requested', 'pending', 'paid', 'failed', 'cancelled'] as const;

const paymentSchema = new mongoose.Schema(
  {
    reference: { type: String, required: true, match: /^PAY-\d{4}-\d{6}$/ },
    student: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    enquiry: { type: mongoose.Schema.Types.ObjectId, ref: 'Enquiry', default: null },
    // Only the consultancy's own charge is collected online; official college fees are paid to colleges.
    purpose: { type: String, enum: ['consultancy_service_charge'], default: 'consultancy_service_charge' },
    description: { type: String, trim: true, maxlength: 200, default: '' },
    amountMinor: { type: Number, required: true, min: 100, validate: Number.isSafeInteger },
    currency: { type: String, enum: ['INR'], default: 'INR' },
    status: { type: String, enum: PAYMENT_STATUSES, default: 'requested', required: true },
    razorpayOrderId: { type: String, default: null },
    razorpayPaymentId: { type: String, default: null },
    receiptNumber: { type: String, default: null },
    paidAt: { type: Date, default: null },
    failureReason: { type: String, maxlength: 300, default: '' },
    requestedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  },
  { timestamps: true },
);
paymentSchema.index({ reference: 1 }, { unique: true, name: 'payment_reference_unique' });
paymentSchema.index({ razorpayOrderId: 1 }, { unique: true, partialFilterExpression: { razorpayOrderId: { $type: 'string' } }, name: 'payment_order_unique' });
paymentSchema.index({ student: 1, createdAt: -1 }, { name: 'payment_by_student' });
paymentSchema.index({ status: 1, createdAt: -1 }, { name: 'payment_by_status' });
export type Payment = InferSchemaType<typeof paymentSchema>;
export const PaymentModel = mongoose.model('Payment', paymentSchema, 'payments');
